/*
 * 省电旋钮 —— 2026-10-03（用户："价签是 2450 电池，需要省电"）
 *
 * 之前的固件是**台式验证版**：主循环 5ms 忙等（CPU 一直在跑）+ 广播永不超时、
 * 间隔 100ms。CR2450（约 600mAh）撑不了多久。这一版开始省电，第一刀砍在两处：
 *
 *   ① 主循环不再忙等：改成 SDK 的 app_timer 节拍（跑在 AON 睡眠定时器上），
 *      配合 pwr_mgmt_mode_set(PMR_MGMT_SLEEP_MODE) —— 没事的时候 CPU 真的睡下去，
 *      AON 定时器到点或 BLE 有事件才醒。这是最大的一笔（CPU 从"一直在跑"变成
 *      "大部分时间在睡"）。
 *   ② 广播间隔 100ms → 1000ms：射频开着的平均电流大致降一个数量级。
 *      基站/网页都是"扫 6 秒、扫到就停"，1 秒的广播间隔照样能被抓到，
 *      代价只是连接建立慢最多 1 秒（屏刷本身要 16 秒，感觉不出来）。
 *
 * ⚠ 这一版**不动 UDS（超深睡）**：原厂那种"醒来等于整个系统复位"的模式，
 *    要先把时间持久化（写 flash）做了才能用，否则每次醒来都是空日历。
 *    现在用的是 SDK 的 SLEEP（深睡、RAM 保持），醒来几毫秒、`s_ts` 和上一屏都在。
 *
 * ⚠ 出问题一键回退：把 ZK_PWR_SAVE 改成 0 —— 立刻回到老行为（200Hz 忙等 + 100ms 广播），
 *    方便判断"是不是省电改动引起的"。回退只需要重编 + 重刷。
 */
#ifndef __ZK_PWR_H__
#define __ZK_PWR_H__

/* ⛔ 2026-10-04 实机结论：**"让 CPU 真睡下去"这条路在这颗芯片上走不通**（暂时关掉）
 *
 * 刷上 build 75 后的实测（status.sh）：
 *   · `heart = 1`      → 主循环**只跑了 1 圈**就再没动过；
 *   · PC 停在 `libble_sdk.a(sdk_pwr_mgmt_patch.o)` 的 RAM 代码里 → CPU **卡在 SDK 的
 *     电源管理代码里打转**；
 *   · `AON 计数器` 连读两次都是 0xFFFFFFFF、时基比值 **0.000** → 低功耗时钟/睡眠定时器
 *     没在跑；
 *   · `IRQ25 BLESLP（BLE 睡眠中断）没使能` → 协议栈醒不过来处理连接；
 *   · 结果：**能广播（BLE 核自己在发，所以基站扫得到）、但连不上**（连接请求没人处理
 *     → 20 秒超时）；`boot_count = 2` 说明不是复位循环，是"卡在里面"。
 *
 * 为什么卡：我们的毫秒时基（build 59）把 **AON 睡眠定时器**当自由计数器用，
 * 而 SDK 的睡眠入口 + app_timer 要**拿同一个定时器**去设唤醒倒计时 ——
 * 两边抢同一个硬件；再加上这颗价签**没有 32.768k 晶振**（走内部 RC，
 * 见 config/custom_config.h 里那段"死在 platform_disable_sleep_timer()"的记录），
 * 睡眠路径本来就敏感。所以：**要睡眠就得先把"谁拥有那个定时器"理清楚**，
 * 不是加两行 pwr_mgmt_mode_set 就能省电的。
 *
 * 结论：先关掉睡眠（0 = 老行为：忙等，CPU 一直跑），**但保留广播间隔那一刀**
 * （下面 ZK_ADV_INTERVAL，它不依赖睡眠、单独就能省射频电流，实测基站照样抓得到）。 */
#define ZK_PWR_SAVE         1

/* 主循环节拍（毫秒）。对 BLE 命令的响应最多晚这么多 —— 屏刷本身 16 秒，
   所以 500ms 完全看不出来；再拉长就更省电、但"命令一来马上动"的感觉会变钝。 */
#define ZK_TICK_MS          500

/* 广播间隔，单位 0.625ms：100ms = 160（**2026-10-04 回退到 100ms**）。
 *
 * 为什么回退：build 75 把它放到 1000ms（1600）之后，基站日志里出现两次
 * "价签从空中消失了"，**两次都紧跟在一次推送之后**（09:47:41 / 09:48:41）——
 * 而 100ms 那几天的日志里从来没这样抖过。抖动的代价不只是日志难看：
 * 基站一"看到它重新出现"就会整包重推（时间+城市名+纪念日）→ **又刷一屏 16 秒**，
 * 跟省电的目标正好相反。
 *
 * 所以：**先回到 100ms 这个被实机验证过几天的配置**。等把"基站存在检测别那么脆"
 * 和"用价签上报的 t= 判断它到底重启没重启"做完（见 base/README），
 * 再重新评估这个间隔 —— 那时候才敢放长。 */
#define ZK_ADV_INTERVAL     160

/* ======================================================================
 * build 90：**广播窗口**（2026-10-14 用户问："就是说你 0 点前后会把广播打开吗"
 *           —— 对，就照这个做）
 *
 * 常开广播（100ms 间隔）按占空比估 ≈0.1 mA ≈ **2.4 mAh/天**，是"一天一次整屏刷新"
 * （0.067 mAh）的 30 多倍。所以只要价签不再需要"随时能被找到"，这一刀最大。
 * 平时不广播，只在这三个时段开窗（判断逻辑在 ble/zk_adv_win.h，主机端有自测）：
 *
 *   ① 上电/复位后 ZK_ADV_BOOT_WINDOW_S 秒之内 —— 刷完机、换电池、想用手机连都靠它；
 *      想手动连就按一下 RST，这个窗口就是"配对键"。
 *   ② 每天 ZK_ADV_DAY_WIN_START_S 起 ZK_ADV_DAY_WIN_LEN_S 秒（默认 23:59:30 + 150 秒，
 *      跨午夜）—— 基站那轮"跨天推送"正好在这时候，顺便每天对一次表。
 *   ③ 每个 ZK_ADV_FB_EVERY_S 秒开 ZK_ADV_FB_LEN_S 秒（默认 6 小时开 30 秒 =
 *      本地 00/06/12/18 点）—— 基站想临时推东西不用干等到第二天 0 点。
 *
 * 三档加起来一天 ≈4 分钟 = **0.28% 占空比**（≈0.007 mAh/天）。
 *
 * ⚠ 前提：**价签自己的钟得准**（build 89 修的），否则它不知道该什么时候开窗。
 * ⚠ 代价（用户已确认）：平时手机网页连不上（要点 RST 开长窗口）；
 *   基站那天没开就推不进来（价签自己照样翻页，屏上只是内容旧一点，不会乱）。
 * ⚠ 出问题一键回退：ZK_ADV_WINDOW 改 0 = 回到 24 小时常开（老行为）。
 * ====================================================================== */
#define ZK_ADV_WINDOW           1
#define ZK_ADV_BOOT_WINDOW_S    300u    /* ① 上电后先开 5 分钟 */
#define ZK_ADV_DAY_WIN_START_S  86370u  /* ② 23:59:30 */
#define ZK_ADV_DAY_WIN_LEN_S    150u    /*   → 一直到 00:02:00 */
#define ZK_ADV_FB_EVERY_S       21600u  /* ③ 每 6 小时 */
#define ZK_ADV_FB_LEN_S         30u     /*   开 30 秒 */

#endif /* __ZK_PWR_H__ */
