/*
 * 省电旋钮 —— 2026-10-03（用户："价签是 2450 电池，需要省电"）
 *
 * 之前的固件是**台式验证版**：主循环 5ms 忙等（CPU 一直在跑）+ 广播永不超时、
 * 间隔 100ms。CR2450（约 600mAh）撑不了多久。这一版开始省电，第一刀砍在两处：
 *
 *   ① 主循环不再忙等：改成 SDK 的 app_timer 节拍（跑在 AON 睡眠定时器上），
 *      配合 pwr_mgmt_mode_set(PMR_MGMT_SLEEP_MODE) —— 没事的时候 CPU 真的睡下去，
 *      AON 定时器到点或 BLE 有事件才醒。这是最大的一笔（CPU 从"一直在跑"变成
 *      "大部分时间在睡"）。
 *   ② 广播间隔 100ms → 1000ms：射频开着的平均电流大致降一个数量级。
 *      基站/网页都是"扫 6 秒、扫到就停"，1 秒的广播间隔照样能被抓到，
 *      代价只是连接建立慢最多 1 秒（屏刷本身要 16 秒，感觉不出来）。
 *
 * ⚠ 这一版**不动 UDS（超深睡）**：原厂那种"醒来等于整个系统复位"的模式，
 *    要先把时间持久化（写 flash）做了才能用，否则每次醒来都是空日历。
 *    现在用的是 SDK 的 SLEEP（深睡、RAM 保持），醒来几毫秒、`s_ts` 和上一屏都在。
 *
 * ⚠ 出问题一键回退：把 ZK_PWR_SAVE 改成 0 —— 立刻回到老行为（200Hz 忙等 + 100ms 广播），
 *    方便判断"是不是省电改动引起的"。回退只需要重编 + 重刷。
 */
#ifndef __ZK_PWR_H__
#define __ZK_PWR_H__

/* ⛔ 2026-10-04 实机结论：**"让 CPU 真睡下去"这条路在这颗芯片上走不通**（暂时关掉）
 *
 * 刷上 build 75 后的实测（status.sh）：
 *   · `heart = 1`      → 主循环**只跑了 1 圈**就再没动过；
 *   · PC 停在 `libble_sdk.a(sdk_pwr_mgmt_patch.o)` 的 RAM 代码里 → CPU **卡在 SDK 的
 *     电源管理代码里打转**；
 *   · `AON 计数器` 连读两次都是 0xFFFFFFFF、时基比值 **0.000** → 低功耗时钟/睡眠定时器
 *     没在跑；
 *   · `IRQ25 BLESLP（BLE 睡眠中断）没使能` → 协议栈醒不过来处理连接；
 *   · 结果：**能广播（BLE 核自己在发，所以基站扫得到）、但连不上**（连接请求没人处理
 *     → 20 秒超时）；`boot_count = 2` 说明不是复位循环，是"卡在里面"。
 *
 * 为什么卡：我们的毫秒时基（build 59）把 **AON 睡眠定时器**当自由计数器用，
 * 而 SDK 的睡眠入口 + app_timer 要**拿同一个定时器**去设唤醒倒计时 ——
 * 两边抢同一个硬件；再加上这颗价签**没有 32.768k 晶振**（走内部 RC，
 * 见 config/custom_config.h 里那段"死在 platform_disable_sleep_timer()"的记录），
 * 睡眠路径本来就敏感。所以：**要睡眠就得先把"谁拥有那个定时器"理清楚**，
 * 不是加两行 pwr_mgmt_mode_set 就能省电的。
 *
 * 结论：先关掉睡眠（0 = 老行为：忙等，CPU 一直跑），**但保留广播间隔那一刀**
 * （下面 ZK_ADV_INTERVAL，它不依赖睡眠、单独就能省射频电流，实测基站照样抓得到）。 */
#define ZK_PWR_SAVE         1

/* 主循环节拍（毫秒）。
 *
 * ⚠ 2026-10-14 build 91：**500 → 2000**。为什么：这个 app_timer 每到期一次，
 *   SDK 就要把 AON 睡眠定时器**重新装载**一次，而"计数器数到 0 → SDK 重新装好"
 *   之间有一段死时间（计数器停在 0 不数了）—— 实测 **每次丢 ≈2.35 ms**。
 *   500ms 一档 = 2 次/秒 ⇒ 每天慢 406 秒（6.8 分钟），这就是 build 89
 *   5 分钟窗口量出来那个 0.996（缺 0.45%）的全部来源。
 *   节拍放到 2 秒 ⇒ 重装少 4 倍 ⇒ 每天慢 ≈102 秒（1.7 分钟）。
 *
 *   为什么敢放这么慢：主循环不需要"勤"—— 接着 USB/蓝牙连着的时候，
 *   协议栈自己的事件（连接间隔几十 ms）本来就会把它叫醒；这个节拍只是
 *   "什么都没有的时候，保证每 N 秒也转一圈"（窗口调度、合并重画到点检查）。
 *   真想要更准再调大（5 秒 ⇒ 每天 0.7 分钟），代价是空转一圈的粒度变粗。 */
/* ⚠ 2026-10-15 晚：**暂时改回 200ms 做一次判别实验**。
 *
 * 19:03 那次 status（build 93、广播已关）发现：79 分钟里价签的钟慢了 **6.7%**
 * （uptime 4749s vs 真实 5088s），而"广播开着"的那几次测量都是 0.996~1.003（准）。
 * 两个嫌疑：
 *   ① **睡太久**（主循环 ~2Hz）导致"睡眠定时器重装"前后的那一段没记全；
 *   ② 低频 RC 在**真正睡下去**时频率比醒着低 ~6%（宿主在"调试器停住 CPU"时量的
 *      是 27233 Hz，而按"2.13 秒走完 54460 tick"反推只有 ~25.5 kHz）。
 * 这一版只把节拍改回 200ms（主循环不再长时间睡）：
 *   · 钟要是变准了 → 是①，修法 = 在睡眠定时器中断里记账（ISR 里补，不等主循环来读）；
 *   · 还是慢 6% → 是②，修法 = 给"睡着状态"单独标定频率系数（或走时基搬家）。
 * 实验做完记得按结论改回来（不然白费射频那笔电）。 */
/* ⚠ 2026-10-15 晚（结论）：200ms 那版把"睡太久"那 6.7% 修掉了，但代价是
   唤醒/重装各多 10 倍（还剩 1.6% 的死时间）。所以**改回 2000ms**，真正的解法
   是 build 95 开始探的"AON 日历计数器"（自由跑、没人重装）—— 探成了就搬过去，
   那时候 2 秒节拍 + 窗口广播都能保留，省电和准都不丢。 */
#define ZK_TICK_MS          2000

/* build 95：AON 日历计数器探针（只探路、不动时基；细节见 main.c 那段注释）。
 *
 * ⛔ 2026-10-15 晚：**关掉、这条路收档**。
 *   实机两版（build 95 装午夜 = 计数值正好 0；build 96 改装 12:34:56）读数**都是
 *   0x00000000**，也就是"装载压根没落进去"（配置本身是对的：EN=1、CLK_SEL=0 =
 *   慢时钟直出、VAL_LOAD 自动清）。最可能是 `CLK_SEL=0` 选的"RTC clock"走的是
 *   **32.768k 晶振那一路，而这颗价签没有那颗晶振**（平台靠内部 RC 顶替）；
 *   次可能是共用的 `AON->TIMER_VALUE` 暂存寄存器被 SDK 抢先改写。
 *   而**现在不需要它了**：build 97 直接量出"睡着时实拿 27199 tick/秒"（对标定
 *   27235 只差 0.13%）、走时比值 1.001 ⇒ 现有这条 AON 睡眠定时器时基本来就够准。
 *   ⇒ 关掉它顺便把 HAL 日历那 ~2.7KB 从镜像里放出来（镜像余量当时只剩 1432 字节）。
 *   想看现场就把这个宏改回 1（代码和自测都留着）。 */
#define ZK_CAL_PROBE        0

/* 广播间隔，单位 0.625ms：100ms = 160（**2026-10-04 回退到 100ms**）。
 *
 * 为什么回退：build 75 把它放到 1000ms（1600）之后，基站日志里出现两次
 * "价签从空中消失了"，**两次都紧跟在一次推送之后**（09:47:41 / 09:48:41）——
 * 而 100ms 那几天的日志里从来没这样抖过。抖动的代价不只是日志难看：
 * 基站一"看到它重新出现"就会整包重推（时间+城市名+纪念日）→ **又刷一屏 16 秒**，
 * 跟省电的目标正好相反。
 *
 * 所以：**先回到 100ms 这个被实机验证过几天的配置**。等把"基站存在检测别那么脆"
 * 和"用价签上报的 t= 判断它到底重启没重启"做完（见 base/README），
 * 再重新评估这个间隔 —— 那时候才敢放长。 */
#define ZK_ADV_INTERVAL     160

/* ======================================================================
 * build 90：**广播窗口**（2026-10-14 用户问："就是说你 0 点前后会把广播打开吗"
 *           —— 对，就照这个做）
 *
 * 常开广播（100ms 间隔）按占空比估 ≈0.1 mA ≈ **2.4 mAh/天**，是"一天一次整屏刷新"
 * （0.067 mAh）的 30 多倍。所以只要价签不再需要"随时能被找到"，这一刀最大。
 * 平时不广播，只在这三个时段开窗（判断逻辑在 ble/zk_adv_win.h，主机端有自测）：
 *
 *   ① 上电/复位后 ZK_ADV_BOOT_WINDOW_S 秒之内 —— 刷完机、换电池、想用手机连都靠它；
 *      想手动连就按一下 RST，这个窗口就是"配对键"。
 *   ② 每天 ZK_ADV_DAY_WIN_START_S 起 ZK_ADV_DAY_WIN_LEN_S 秒（默认 23:59:30 + 150 秒，
 *      跨午夜）—— 基站那轮"跨天推送"正好在这时候，顺便每天对一次表。
 *   ③ 每个 ZK_ADV_FB_EVERY_S 秒开 ZK_ADV_FB_LEN_S 秒（默认 6 小时开 30 秒 =
 *      本地 00/06/12/18 点）—— 基站想临时推东西不用干等到第二天 0 点。
 *
 * 三档加起来一天 ≈4 分钟 = **0.28% 占空比**（≈0.007 mAh/天）。
 *
 * ⚠ 前提：**价签自己的钟得准**（build 89 修的），否则它不知道该什么时候开窗。
 * ⚠ 代价（用户已确认）：平时手机网页连不上（要点 RST 开长窗口）；
 *   基站那天没开就推不进来（价签自己照样翻页，屏上只是内容旧一点，不会乱）。
 * ⚠ 出问题一键回退：ZK_ADV_WINDOW 改 0 = 回到 24 小时常开（老行为）。
 * ====================================================================== */
#define ZK_ADV_WINDOW           1
#define ZK_ADV_BOOT_WINDOW_S    300u    /* ① 上电后先开 5 分钟 */
/* ② 每天这一窗：**放 20 分钟宽**（23:50:00 → 00:10:00），不是掐着 0 点那一两分钟。
   为什么故意放宽：这个窗口是按"价签自己认为的现在几点"算的，而频源是内部 RC
   （LPRC）—— 哪怕时基比值已经很准，几个月下来也可能漂出几分钟到十几分钟。
   窗口太窄的话，漂出去就**永远接不到基站那轮跨天推送**了；20 分钟足够罩住漂移，
   代价只是 1200 秒/天 = 1.4% 占空比（比常开还是小 70 倍）。 */
#define ZK_ADV_DAY_WIN_START_S  85800u  /* ② 23:50:00 */
#define ZK_ADV_DAY_WIN_LEN_S    1200u   /*   → 一直到 00:10:00 */
#define ZK_ADV_FB_EVERY_S       21600u  /* ③ 每 6 小时 */
#define ZK_ADV_FB_LEN_S         30u     /*   开 30 秒 */

/* ======================================================================
 * 2026-10-16 晚：**不做方案区分了**（用户改主意，原话）：
 *
 *   "还是不区分方案了，如果天气是一整天的比如晴转多云，温度是当天的区间 24-31 度，
 *    这样就只需要 0 点刷新，也就没有省电不省电的区分了。"
 *
 *   ⇒ 一套行为就好：广播走窗口（省电那一刀仍然要）、**天气按"天"给**（当天整体天气
 *     ＋当天温度区间）、屏上只在 0 点那一次更新。
 *   ⇒ "天气一变就刷屏"这件事从根上没了（天气一天只变一次），所以既不需要
 *     "去掉天气"，也不需要"省电/常电"那种方案区分。
 *   ⇒ build 99（编译期两套）和 build 100（运行时 0x74 切换）都撤掉，回到一套固件。
 * ====================================================================== */

/* 0 点那次：**价签自己的"换天翻页"要等一下基站的推送**（见 zk_epd_svc.c）。
   为什么：基站那轮推下来的会带**当天的新天气**；价签要是 00:00:00 先自己翻一页
   （画上还是昨天那份天气），5 秒后基站再推一次（天气变了）→ 一天白刷两次。
   所以先等这么多秒、把机会让给基站；到点还没人来，价签再自己翻（不依赖基站）。 */
#define ZK_FLIP_GRACE_S     120u

/* ======================================================================
 * build 103（2026-10-18 用户量了电流："开机2.1mA，然后一直是1.7到2.1跳变"）
 *
 * 这个量级（≈1.9mA）不是广播窗口能解释的：600mAh ÷ 1.9mA ≈ **12 天**。
 * GR551x 的 **IDLE 档本身**就是 mA 级（只把 CPU 停在 WFE，模拟/时钟都在跑）；
 * 要 µA 必须进 **SLEEP 档**（深睡，RAM 保持）。这一版先做两件事，都是**可测**的：
 *
 *   ① **刷完让面板自己深睡**（0x10 0x01）—— 以前只 `epd_pins_release()` 松 GPIO，
 *      面板内部的升压不会因此关掉（墨水屏的经典坑：PON 状态空转 0.5~2mA）。
 *      flush 开头本来就有硬复位，所以下一轮照样能唤醒。
 *   ② **运行时切 PMU 档**（BLE 命令 0x9C）—— 一次刷机就能量一条阶梯：
 *        9C 00 ACTIVE（地板对照）· 9C 01 IDLE（默认）·
 *        9C 02 SLEEP（真深睡，⚠ 历史上挂过两次）· 9C 03 IDLE+广播强制关（剔掉射频）。
 *      档只改 RAM，**重启就回到默认 IDLE**；万一 9C 02 把链路睡坏，拔电池/按 RST 即回。
 * ====================================================================== */
#define ZK_PWR_DEFAULT_MODE      1u
#define ZK_PWR_MODE_ACTIVE       0u
#define ZK_PWR_MODE_IDLE         1u
#define ZK_PWR_MODE_SLEEP        2u   /* ⚠ 历史上挂过两次；这一版拿来实测"到底行不行" */
#define ZK_PWR_MODE_IDLE_NORADIO 3u   /* IDLE + 广播强制关（把射频这一项从账里剔掉） */

/* 刷完要不要让面板进深睡（1 = 要）。改成 0 重编 = 回到"只松 GPIO"的老行为。 */
#define ZK_EPD_DEEP_SLEEP_AFTER_REFRESH 1

/* 由 main.c 实现；BLE 服务（0x9C）和广播窗口都要问它 */
void    zk_pwr_set_mode(uint8_t mode);      /* 0..3，只改 RAM */
uint8_t zk_pwr_get_mode(void);
uint8_t zk_pwr_adv_forced_off(void);        /* 1 = 广播被强制关（档 3） */

#endif /* __ZK_PWR_H__ */
