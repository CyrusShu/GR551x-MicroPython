/* 和风预警编号 -> 图标下标；认不出的返回 0（通用预警） */
static const struct { uint16_t code; uint8_t idx; } s_alert_map[] = {
    { 1003, 1 },   /* 暴雨 */
    { 1014, 2 },   /* 雷电 */
    { 1001, 3 },   /* 台风 */
    { 1015, 4 },   /* 冰雹 */
    { 1009, 5 },   /* 高温 */
};

const uint8_t *zk_alert_icon(int qweather_code)
{
    unsigned i;

    for (i = 0; i < sizeof(s_alert_map) / sizeof(s_alert_map[0]); i++)
    {
        if ((int)s_alert_map[i].code == qweather_code)
        {
            return s_alert_icon[s_alert_map[i].idx];
        }
    }
    return s_alert_icon[0];        /* 通用预警兜底 */
}
