const char *zk_weather_name(uint8_t code)
{
    return (code <= ZK_WX_MAX) ? s_wx_name[code] : "?";
}

const uint32_t *zk_weather_text(uint8_t code)
{
    return (code <= ZK_WX_MAX) ? s_wx_text[code] : s_wx_text[0];
}

const uint8_t *zk_weather_icon(uint8_t code)
{
    return (code >= 1u && code <= ZK_WX_MAX) ? s_wx_icon[code] : 0;
}

const uint8_t *zk_weather_glyph(uint32_t cp)
{
    int i;

    for (i = 0; i < 12; i++)
    {
        if (s_wx_glyph_cp[i] == cp)
        {
            return s_wx_glyph[i];
        }
    }
    return 0;
}
